const router=require('express').Router();
const config=require('../../config');
const {autenticar,autorizar}=require('../../middlewares/auth');
const servicio=require('./service');
router.use(autenticar,autorizar(config.roles.ADMIN, config.roles.BODEGA));
router.get('/',async(req,res)=>res.json(await servicio.listar(req.query)));
router.get('/articulos/:id/pendientes',async(req,res)=>res.json(await servicio.pendientesArticulo(req.params.id,req.query)));
router.get('/:id',async(req,res)=>res.json(await servicio.obtener(req.params.id)));
router.post('/:id',async(req,res)=>res.json(await servicio.recibir(req.params.id,req.body||{},req.user.id_usuario)));
module.exports=router;
